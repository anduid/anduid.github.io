    /* ==========================================================
       2. INDEXEDDB ENGINE IMPLEMENTATION (Zero-Leak Persistence)
       ========================================================= */
    let dbInstance = null;
    const DB_NAME = 'ANDU_Terminal_EnterpriseDB';
    const DB_VERSION = 1;

    function initIndexedDB() {
      return new Promise((resolve) => {
        const request = indexedDB.open(DB_NAME, DB_VERSION);

        request.onupgradeneeded = (e) => {
          const db = e.target.result;
          if (!db.objectStoreNames.contains('user')) {
            db.createObjectStore('user', { keyPath: 'id' });
          }
          if (!db.objectStoreNames.contains('licenses')) {
            db.createObjectStore('licenses', { keyPath: 'id', autoIncrement: true });
          }
          if (!db.objectStoreNames.contains('projects')) {
            db.createObjectStore('projects', { keyPath: 'id', autoIncrement: true });
          }
          if (!db.objectStoreNames.contains('courses')) {
            db.createObjectStore('courses', { keyPath: 'id' });
          }
          if (!db.objectStoreNames.contains('vault_tasks')) {
            db.createObjectStore('vault_tasks', { keyPath: 'id', autoIncrement: true });
          }
          if (!db.objectStoreNames.contains('notifications')) {
            db.createObjectStore('notifications', { keyPath: 'id', autoIncrement: true });
          }
        };

        request.onsuccess = (e) => {
          dbInstance = e.target.result;
          resolve(dbInstance);
        };

        request.onerror = () => resolve(null);
      });
    }

    const dbQuery = (storeName, mode) => dbInstance.transaction(storeName, mode).objectStore(storeName);
    const dbGetAll = (storeName) => new Promise(res => {
      if (!dbInstance) return res([]);
      const req = dbQuery(storeName, 'readonly').getAll();
      req.onsuccess = () => res(req.result || []);
      req.onerror = () => res([]);
    });
    const dbPut = (storeName, data) => new Promise(res => {
      if (!dbInstance) return res(null);
      const req = dbQuery(storeName, 'readwrite').put(data);
      req.onsuccess = () => res(req.result);
      req.onerror = () => res(null);
    });
    const dbDelete = (storeName, key) => new Promise(res => {
      if (!dbInstance) return res(null);
      const req = dbQuery(storeName, 'readwrite').delete(key);
      req.onsuccess = () => res(true);
      req.onerror = () => res(false);
    });
    const dbClear = (storeName) => new Promise(res => {
      if (!dbInstance) return res(null);
      const req = dbQuery(storeName, 'readwrite').clear();
      req.onsuccess = () => res(true);
      req.onerror = () => res(false);
    });

